import { env } from '@beauty-salon-frontend/config'

const REQUEST_TIMEOUT_MS = 30_000

type HttpResponse = {
  data: unknown
  status: number
  headers: Headers
}

const isJsonMediaType = (contentType: string): boolean => {
  const [mediaType = ''] = contentType.split(';')
  const essence = mediaType.trim().toLowerCase()

  return essence === 'application/json' || essence.endsWith('+json')
}

const parseBody = (text: string, contentType: string): unknown => {
  if (text === '') {
    return undefined
  }

  return isJsonMediaType(contentType) ? JSON.parse(text) : text
}

const withTimeout = (signal: AbortSignal | null | undefined): AbortSignal => {
  const timeout = AbortSignal.timeout(REQUEST_TIMEOUT_MS)

  return signal ? AbortSignal.any([signal, timeout]) : timeout
}

/**
 * The HTTP function that the API client generated by Orval calls for every
 * request.
 *
 * Every HTTP status resolves to `{ data, status, headers }`: an error response
 * of the API is a value that the caller matches on `status`. The promise
 * rejects only when there is no response to return: the network failed, the
 * caller's signal or the timeout aborted the request, the body is not the
 * JSON that its `Content-Type` announces, or `VITE_BACKEND_BASE_URL` is not
 * set.
 *
 * `T` is the response type that the generated code names for the operation.
 * The body is not checked against it at runtime: the OpenAPI document that
 * the client and the server are generated from is the contract.
 */
export function customInstance<T>(url: string, options: RequestInit): Promise<T>
export async function customInstance(
  url: string,
  options: RequestInit,
): Promise<HttpResponse> {
  const origin = env.VITE_BACKEND_BASE_URL.value
  if (origin === undefined) {
    return Promise.reject(new Error('VITE_BACKEND_BASE_URL is not set'))
  }

  const response = await fetch(`${origin}${url}`, {
    ...options,
    signal: withTimeout(options.signal),
  })
  const text = await response.text()

  return {
    data: parseBody(text, response.headers.get('content-type') ?? ''),
    status: response.status,
    headers: response.headers,
  }
}
