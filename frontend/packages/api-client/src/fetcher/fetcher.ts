import { env } from '@beauty-salon-frontend/config'
import { type StoredSession, sessionStore } from '@beauty-salon-frontend/io'
import { match } from 'ts-pattern'
import * as z from 'zod/mini'
// The module of the codes alone: the index of the models loads all 777 of them
import { ModelsErrorCodeType } from '../generated/models/modelsErrorCodeType'
import type { ModelsProblemDetails } from '../generated/models/modelsProblemDetails'
import { renewSession, sessionAfterRejectionOf } from './renew-session'

const REQUEST_TIMEOUT_MS = 30_000

type HttpResponse = {
  data: unknown
  status: number
  headers: Headers
}

/** What is read of a problem of the API: its code */
const problemSchema = z.object({
  code: z.enum(ModelsErrorCodeType),
}) satisfies z.ZodMiniType<Pick<ModelsProblemDetails, 'code'>>

const isJsonMediaType = (contentType: string): boolean => {
  const [mediaType = ''] = contentType.split(';')
  const essence = mediaType.trim().toLowerCase()

  return essence === 'application/json' || essence.endsWith('+json')
}

const parseBody = (text: string, contentType: string): unknown => {
  if (text === '') {
    return undefined
  }

  return isJsonMediaType(contentType) ? JSON.parse(text) : text
}

const withTimeout = (signal: AbortSignal | null | undefined): AbortSignal => {
  const timeout = AbortSignal.timeout(REQUEST_TIMEOUT_MS)

  return signal ? AbortSignal.any([signal, timeout]) : timeout
}

const withAccessToken = (
  headers: HeadersInit | undefined,
  session: StoredSession | null,
): Headers => {
  const sent = new Headers(headers)
  if (session !== null) {
    sent.set('Authorization', `Bearer ${session.accessToken}`)
  }

  return sent
}

const send = async (
  url: string,
  options: RequestInit,
  session: StoredSession | null,
): Promise<HttpResponse> => {
  const response = await fetch(url, {
    ...options,
    headers: withAccessToken(options.headers, session),
    signal: withTimeout(options.signal),
  })
  const text = await response.text()

  return {
    data: parseBody(text, response.headers.get('content-type') ?? ''),
    status: response.status,
    headers: response.headers,
  }
}

/**
 * The session to send the request again with, after the API answered 401 to
 * the one that was sent with `session`; null when the answer stands.
 */
const sessionToRetryWith = (
  origin: string,
  session: StoredSession,
  response: HttpResponse,
): Promise<StoredSession | null> => {
  const problem = problemSchema.safeParse(response.data)

  return (
    match(problem.success ? problem.data.code : null)
      // The two codes of a 401 that is about the access token (docs/authentication.md)
      .with(ModelsErrorCodeType.NUMBER_1003, () =>
        renewSession(origin, session),
      )
      .with(ModelsErrorCodeType.NUMBER_1004, async () =>
        sessionAfterRejectionOf(session),
      )
      .otherwise(async () => null)
  )
}

/**
 * The HTTP function that the API client generated by Orval calls for every
 * request.
 *
 * Every HTTP status resolves to `{ data, status, headers }`: an error response
 * of the API is a value that the caller matches on `status`. The promise
 * rejects only when there is no response to return: the network failed, the
 * caller's signal or the timeout aborted the request, the body is not the
 * JSON that its `Content-Type` announces, or `VITE_BACKEND_BASE_URL` is not
 * set.
 *
 * While a session is stored (`sessionStore`), the request carries its access
 * token. When the API answers that the token has expired, the session is
 * renewed and the request is sent once more, with the new token; the caller
 * gets the answer to that second request. When the session cannot be renewed
 * the caller gets the 401, and where the API said that the session is over,
 * the stored session is gone: whoever listens to `sessionStore` sees the user
 * signed out.
 *
 * `T` is the response type that the generated code names for the operation.
 * The body is not checked against it at runtime: the OpenAPI document that
 * the client and the server are generated from is the contract.
 */
export function customInstance<T>(url: string, options: RequestInit): Promise<T>
export async function customInstance(
  url: string,
  options: RequestInit,
): Promise<HttpResponse> {
  const origin = env.VITE_BACKEND_BASE_URL.value
  if (origin === undefined) {
    return Promise.reject(new Error('VITE_BACKEND_BASE_URL is not set'))
  }

  const session = sessionStore.read()
  const response = await send(`${origin}${url}`, options, session)
  if (session === null || response.status !== 401) {
    return response
  }

  const next = await sessionToRetryWith(origin, session, response)

  return next === null ? response : send(`${origin}${url}`, options, next)
}
